export const EXCLUDED_ALT = "__excluded__";

export function isExclusionRow(row) {
  return (
    row?.alt === EXCLUDED_ALT &&
    typeof row?.image_url === "string" &&
    row.image_url.startsWith("builtin://")
  );
}
